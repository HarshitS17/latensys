package com.harshit.monitoring;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

import static org.junit.jupiter.api.Assertions.assertEquals;

@Testcontainers
class MigrationCompatibilityTest {
    @Container
    static final PostgreSQLContainer<?> postgres = new PostgreSQLContainer<>("postgres:16.6-alpine");

    @Test
    void explicitBaselinePreservesExistingM0AndM1Rows() throws Exception {
        migrateExisting("legacy_m0", false);
        migrateExisting("legacy_m1", true);
    }

    private void migrateExisting(String schema, boolean hasDecision) throws Exception {
        try (Connection connection = DriverManager.getConnection(postgres.getJdbcUrl(),
                postgres.getUsername(), postgres.getPassword()); Statement statement = connection.createStatement()) {
            statement.execute("CREATE SCHEMA " + schema);
            statement.execute("CREATE TABLE " + schema + ".api_request_logs ("
                    + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "method VARCHAR(255), uri VARCHAR(255), status INTEGER NOT NULL, "
                    + "response_time BIGINT NOT NULL, timestamp TIMESTAMP(6)"
                    + (hasDecision ? ", decision VARCHAR(255)" : "") + ")");
            statement.execute("INSERT INTO " + schema + ".api_request_logs "
                    + "(method,uri,status,response_time,timestamp"
                    + (hasDecision ? ",decision" : "") + ") VALUES "
                    + "('GET','/legacy',200,25,CURRENT_TIMESTAMP"
                    + (hasDecision ? ",'ALLOWED'" : "") + ")");
        }

        Flyway flyway = Flyway.configure().dataSource(postgres.getJdbcUrl(),
                        postgres.getUsername(), postgres.getPassword())
                .schemas(schema).defaultSchema(schema).baselineVersion("1")
                .locations("classpath:db/migration").load();
        flyway.baseline(); // Explicit one-time operator action; application auto-baselining stays disabled.
        flyway.migrate();

        try (Connection connection = DriverManager.getConnection(postgres.getJdbcUrl(),
                postgres.getUsername(), postgres.getPassword()); Statement statement = connection.createStatement()) {
            try (ResultSet rows = statement.executeQuery("SELECT COUNT(*) FROM " + schema + ".api_request_logs")) {
                rows.next();
                assertEquals(1, rows.getLong(1));
            }
            try (ResultSet columns = statement.executeQuery("SELECT COUNT(*) FROM information_schema.columns "
                    + "WHERE table_schema='" + schema + "' AND table_name='api_request_logs' AND column_name='decision'")) {
                columns.next();
                assertEquals(1, columns.getLong(1));
            }
            try (ResultSet indexes = statement.executeQuery("SELECT COUNT(*) FROM pg_indexes "
                    + "WHERE schemaname='" + schema + "' AND tablename='api_request_logs' "
                    + "AND indexname = 'idx_request_logs_timestamp'")) {
                indexes.next();
                assertEquals(1, indexes.getLong(1));
            }
        }
    }
}
